bool encoder_update_user(uint8_t index, bool clockwise) {
// ┌───────────────────────────────────────────────────────────┐
// │ e n c o d e r  L                                          │
// └───────────────────────────────────────────────────────────┘
    if (index == 0) {
        if (clockwise) {
            tap_code(KC_VOLD);
        } else {
            tap_code(KC_VOLU);
        }

// ┌───────────────────────────────────────────────────────────┐
// │ e n c o d e r  R                                          │
// └───────────────────────────────────────────────────────────┘
    } else if (index == 1) {
        if (IS_LAYER_ON(_MOUSE)) {
            if (clockwise) {
                tap_code(MS_WHLL);
            } else {
                tap_code(MS_WHLR);
            }
        } else {
            if (clockwise) {
                tap_code(MS_WHLD);
            } else {
                tap_code(MS_WHLU);
            }
        }
    }
    return false;
}
